# Kesamaan dan ketidaksamaan string
fruit = 'blueberry'
print("\nIs fruit == 'blueberry'? I predict True.")
print(fruit == 'blueberry')
print("\nIs fruit == 'mango'? I predict False.")
print(fruit == 'mango')
print("\nIs fruit != 'mango'? I predict True.")
print(fruit != 'mango')
print("\nIs fruit != 'blueberry'? I predict False.")
print(fruit != 'blueberry')
# Tes dengan method lower()
city = 'Solo'
print("\nIs city.lower() == 'solo'? I predict True.")
print(city.lower() == 'solo')
print("\nIs city.lower() == 'Solo'? I predict False.")
print(city.lower() == 'Solo')
# Tes angka: ==, !=, >, <, >=, <=
number = 10
print("\nIs number == 10? I predict True.")
print(number == 10)
print("\nIs number != 10? I predict False.")
print(number != 10)
print("\nIs number > 5? I predict True.")
print(number > 5)
print("\nIs number < 5? I predict False.")
print(number < 5)
print("\nIs number >= 10? I predict True.")
print(number >= 10)
print("\nIs number <= 9? I predict False.")
print(number <= 9)
# Tes dengan and dan or
person_age = 22
print("\nIs person_age > 18 and person_age < 30? I predict True.")
print(person_age > 18 and person_age < 30)
print("\nIs person_age > 18 and person_age < 20? I predict False.")
print(person_age > 18 and person_age < 20)
print("\nIs person_age < 18 or person_age > 20? I predict True.")
print(person_age < 18 or person_age > 20)
print("\nIs person_age < 18 or person_age > 25? I predict False.")
print(person_age < 18 or person_age > 25)
# Tes item ada di dalam list (in)
fruits = ['apple', 'banana', 'cherry']
print("\nIs 'banana' in fruits? I predict True.")
print('banana' in fruits)
print("\nIs 'grape' in fruits? I predict False.")
print('grape' in fruits)
# Tes item tidak ada di dalam list (not in)
print("\nIs 'grape' not in fruits? I predict True.")
print('grape' not in fruits)
print("\nIs 'banana' not in fruits? I predict False.")
print('banana' not in fruits)